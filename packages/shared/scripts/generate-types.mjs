#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputs = [
  {
    schemaPath: "schemas/conversation-sessions.v1.schema.json",
    outputPath: "src/generated/conversation-sessions.v1.ts",
    identifier: "clerkmesh.conversation-sessions.v1",
    render: (id) => `// Generated by packages/shared/scripts/generate-types.mjs. Do not edit.\n\nexport interface ConversationSessionV1 {\n  id: string;\n  name: string | null;\n  createdAt: string;\n  modifiedAt: string;\n  messageCount: number;\n}\n\nexport interface ConversationSessionsV1 {\n  schema: "${id}";\n  observedAt: string;\n  sessions: ConversationSessionV1[];\n  errors: string[];\n}\n`,
  },
  {
    schemaPath: "schemas/conversation-events.v1.schema.json",
    outputPath: "src/generated/conversation-events.v1.ts",
    identifier: "clerkmesh.conversation-events.v1",
    render: (id) => `// Generated by packages/shared/scripts/generate-types.mjs. Do not edit.\n\nexport type ConversationEventKindV1 = "visible-message" | "stream-fragment" | "notification" | "error" | "primary-status" | "extension-ui" | "diagnostic";\n\nexport interface ConversationEventV1 {\n  sequence: number;\n  kind: ConversationEventKindV1;\n  payload: Record<string, unknown>;\n}\n\nexport interface ConversationEventsV1 {\n  schema: "${id}";\n  observedAt: string;\n  cursor: number;\n  events: ConversationEventV1[];\n}\n`,
  },
];

for (const item of outputs) {
  const schemaPath = resolve(root, item.schemaPath);
  const outputPath = resolve(root, item.outputPath);
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  if (schema.properties?.schema?.const !== item.identifier) throw new Error(`unexpected schema identifier: ${schemaPath}`);
  const output = item.render(item.identifier);
  if (process.argv.includes("--check")) {
    if (readFileSync(outputPath, "utf8") !== output) throw new Error(`generated type is stale: ${outputPath}`);
  } else {
    writeFileSync(outputPath, output);
  }
}
